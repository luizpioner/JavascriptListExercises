function calcularOperacoes(valor1, valor2){
	console.log("Soma",valor1 + valor2);
	console.log("Subtracao:",valor1 - valor2);
	console.log("Multiplicaco:",valor1 * valor2);
	console.log("Divisao:", valor1 / valor2);
	console.log("Potencia:",Math.pow(valor1,valor2));
}
calcularOperacoes(2, 3);